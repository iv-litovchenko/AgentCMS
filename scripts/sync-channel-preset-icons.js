#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");
const { CHANNEL_PRESET_ICON_MAP } = require("../lib/config/channel-preset-icon-map");

const ROOT = path.join(__dirname, "..");
const LUCIDE_DIR = path.join(ROOT, "node_modules", "lucide-static", "icons");
const SIMPLE_DIR = path.join(ROOT, "node_modules", "simple-icons", "icons");
const OUT_DIR = path.join(ROOT, "public", "vendor", "channel-preset-icons");
const MAP_JS = path.join(OUT_DIR, "map.js");

function readIconSvg(pack, name) {
  const base = pack === "simple" ? SIMPLE_DIR : LUCIDE_DIR;
  const filePath = path.join(base, `${name}.svg`);
  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing icon file: ${filePath}`);
  }
  return fs.readFileSync(filePath, "utf-8");
}

function normalizeLucideSvg(raw) {
  let svg = raw
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\sclass="[^"]*"/g, "")
    .trim();
  // Только корневой <svg> — у дочерних <rect> width/height обязательны
  svg = svg.replace(/(<svg\b[^>]*)\swidth="[^"]*"/, "$1");
  svg = svg.replace(/(<svg\b[^>]*)\sheight="[^"]*"/, "$1");
  return svg;
}

function normalizeSimpleSvg(raw) {
  let svg = raw.replace(/<title>[\s\S]*?<\/title>/gi, "").trim();
  svg = svg.replace(/<path /g, '<path fill="currentColor" ');
  return svg;
}

function inlineSvgForEntry(entry) {
  const raw = readIconSvg(entry.pack, entry.name);
  return entry.pack === "simple" ? normalizeSimpleSvg(raw) : normalizeLucideSvg(raw);
}

function main() {
  if (!fs.existsSync(LUCIDE_DIR) || !fs.existsSync(SIMPLE_DIR)) {
    console.warn(
      "[sync-channel-preset-icons] Skip: install devDependencies lucide-static and simple-icons"
    );
    return;
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });

  const inlineBySlug = {};
  for (const [slug, ref] of Object.entries(CHANNEL_PRESET_ICON_MAP)) {
    const svg = inlineSvgForEntry(ref);
    inlineBySlug[slug] = svg;
    fs.writeFileSync(path.join(OUT_DIR, `${slug}.svg`), `${svg}\n`, "utf-8");
  }

  const mapBody = JSON.stringify(inlineBySlug, null, 2);
  const js = `/* Generated by scripts/sync-channel-preset-icons.js — do not edit */
(function (global) {
  global.CHANNEL_PRESET_ICON_SVG = ${mapBody};
})(typeof window !== "undefined" ? window : global);
`;
  fs.writeFileSync(MAP_JS, js, "utf-8");
  console.log(`[sync-channel-preset-icons] Wrote ${Object.keys(inlineBySlug).length} icons → ${OUT_DIR}`);
}

main();
