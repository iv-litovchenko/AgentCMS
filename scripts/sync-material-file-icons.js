#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const THEME_ROOT = path.join(ROOT, "node_modules", "material-icon-theme");
const ICONS_SRC = path.join(THEME_ROOT, "icons");
const THEME_JSON = path.join(THEME_ROOT, "dist", "material-icons.json");
const OUT_DIR = path.join(ROOT, "public", "vendor", "material-file-icons");
const MAP_JS = path.join(OUT_DIR, "map.js");

/** Extensions we care about in the CMS (entry overview + document viewer). */
const EXTENSIONS = [
  "png",
  "jpg",
  "jpeg",
  "gif",
  "webp",
  "svg",
  "avif",
  "bmp",
  "ico",
  "mp4",
  "webm",
  "mov",
  "mkv",
  "avi",
  "m4v",
  "ogv",
  "mp3",
  "wav",
  "ogg",
  "m4a",
  "flac",
  "aac",
  "opus",
  "weba",
  "zip",
  "rar",
  "7z",
  "tar",
  "gz",
  "tgz",
  "bz2",
  "xz",
  "pdf",
  "doc",
  "docx",
  "xls",
  "xlsx",
  "ppt",
  "pptx",
  "txt",
  "md",
  "rtf",
  "csv",
  "log",
  "env",
  "ini",
  "js",
  "ts",
  "tsx",
  "jsx",
  "json",
  "yaml",
  "yml",
  "html",
  "css",
  "py",
  "sh",
  "sql",
  "xml"
];

function main() {
  if (!fs.existsSync(THEME_JSON)) {
    console.error("material-icon-theme is not installed. Run: npm install");
    process.exit(1);
  }

  const theme = JSON.parse(fs.readFileSync(THEME_JSON, "utf8"));
  const { iconDefinitions, fileExtensions, file } = theme;
  const defaultIconId = file || "file";

  const byExt = {};
  const svgFiles = new Set();

  function resolveSvgFile(iconId) {
    const def = iconDefinitions[iconId] || iconDefinitions[defaultIconId];
    if (!def?.iconPath) return "file.svg";
    const base = path.basename(def.iconPath);
    return base.endsWith(".svg") ? base : `${iconId}.svg`;
  }

  for (const ext of EXTENSIONS) {
    const iconId = fileExtensions[ext] || defaultIconId;
    const svgName = resolveSvgFile(iconId);
    byExt[`.${ext}`] = svgName;
    svgFiles.add(svgName);
  }

  const defaultSvg = resolveSvgFile(defaultIconId);
  svgFiles.add(defaultSvg);

  fs.mkdirSync(OUT_DIR, { recursive: true });

  for (const name of svgFiles) {
    const src = path.join(ICONS_SRC, name);
    const dest = path.join(OUT_DIR, name);
    if (!fs.existsSync(src)) {
      console.warn(`skip missing icon: ${name}`);
      continue;
    }
    fs.copyFileSync(src, dest);
  }

  const licenseSrc = path.join(THEME_ROOT, "LICENSE");
  if (fs.existsSync(licenseSrc)) {
    fs.copyFileSync(licenseSrc, path.join(OUT_DIR, "LICENSE"));
  }

  const mapPayload = {
    base: "/vendor/material-file-icons/",
    default: defaultSvg,
    byExt
  };

  fs.writeFileSync(
    MAP_JS,
    `/* Generated by scripts/sync-material-file-icons.js — do not edit */\nwindow.MATERIAL_FILE_ICONS = ${JSON.stringify(mapPayload, null, 2)};\n`,
    "utf8"
  );

  console.log(
    `material-file-icons: ${svgFiles.size} SVG(s), ${Object.keys(byExt).length} extension(s) → ${path.relative(ROOT, OUT_DIR)}`
  );
}

main();
