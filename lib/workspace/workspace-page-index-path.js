const {
  AWN_TOPICS_ROOT_FOLDER,
  AWN_TOPICS_INDEX_REL,
  WORKSPACE_PAGE_INDEX_LEGACY_REL,
  AWN_TOPICS_INDEX_LEGACY_UPPER_REL
} = require("../config/manifest-paths");

function getWorkspacePageIndexRelPath() {
  return AWN_TOPICS_INDEX_REL;
}

function getWorkspacePageIndexLegacyRelPaths() {
  return [WORKSPACE_PAGE_INDEX_LEGACY_REL, AWN_TOPICS_INDEX_LEGACY_UPPER_REL];
}

function getWorkspacePageIndexHistoryManifestRel() {
  return `${AWN_TOPICS_ROOT_FOLDER}/manifest.md`;
}

function normalizeWorkspaceIndexMarkdownRel(relPath) {
  return String(relPath || "").replace(/\\/g, "/").replace(/^\/+/, "").trim();
}

function isWorkspacePageIndexMarkdownRel(relPath) {
  const p = normalizeWorkspaceIndexMarkdownRel(relPath).toLowerCase();
  if (!p) return false;
  if (p === getWorkspacePageIndexRelPath().toLowerCase()) return true;
  return getWorkspacePageIndexLegacyRelPaths().some((legacy) => legacy.toLowerCase() === p);
}

/** Autogenerated markdown TOCs (not manifest.md) readable via GET /api/file. */
function isWorkspaceTocMarkdownRel(relPath) {
  const p = normalizeWorkspaceIndexMarkdownRel(relPath);
  if (!p) return false;
  const lower = p.toLowerCase();
  if (isWorkspacePageIndexMarkdownRel(p)) return true;
  if (lower === "ws-map.md" || lower === "wsmap.md") return true;
  if (/^awn-(?:databases|channels|media|repositories)\/index\.md$/i.test(lower)) return true;
  if (/\/index\.md$/i.test(lower)) return true;
  return false;
}

/** @param {(rel: string) => Promise<boolean>} workspaceRelFileExists */
async function resolveWorkspacePageIndexFileOnDisk(workspaceRelFileExists) {
  const canonical = getWorkspacePageIndexRelPath();
  if (await workspaceRelFileExists(canonical)) {
    return { path: canonical, exists: true, legacy: false };
  }
  for (const legacy of getWorkspacePageIndexLegacyRelPaths()) {
    if (!legacy || legacy.toLowerCase() === canonical.toLowerCase()) continue;
    if (await workspaceRelFileExists(legacy)) {
      return { path: legacy, exists: true, legacy: true, canonicalPath: canonical };
    }
  }
  return { path: canonical, exists: false, legacy: false };
}

module.exports = {
  getWorkspacePageIndexRelPath,
  getWorkspacePageIndexLegacyRelPaths,
  getWorkspacePageIndexHistoryManifestRel,
  resolveWorkspacePageIndexFileOnDisk,
  isWorkspacePageIndexMarkdownRel,
  isWorkspaceTocMarkdownRel
};
